import { createHash } from 'node:crypto';

export const EXPECTED_SCENARIO_COUNT = 480;
export const FEATURE_HEADER = 'generated by .tools/gen-bdd-features.mjs from .docs/e2e/BDD.md';

const SCENARIO_RE = /^\s*Scenario:\s+\[[^\]]*\]\s+(E2E-\d{3})\s+(.+?)\s*$/;
const STEP_RE = /^\s*(Given|When|Then|And|But)\s+(.+?)\s*$/;

export function slugify(value) {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-')
    .slice(0, 80);
}

function parseBlock(block, area, subarea) {
  const tags = [];
  let name = '';
  const scenarios = [];
  let current = null;
  let currentKeyword = 'Given';
  let sawFeature = false;

  for (let offset = 0; offset < block.lines.length; offset += 1) {
    const raw = block.lines[offset];
    const line = raw.replace(/\r$/, '');
    const trimmed = line.trim();
    if (!sawFeature) {
      if (trimmed.startsWith('@')) {
        tags.push(...trimmed.split(/\s+/).filter(Boolean));
        continue;
      }
      const featureMatch = /^Feature:\s+(.+?)\s*$/.exec(trimmed);
      if (featureMatch) {
        name = featureMatch[1];
        sawFeature = true;
        continue;
      }
      if (trimmed === '') continue;
      continue;
    }

    const scenarioMatch = SCENARIO_RE.exec(line);
    if (scenarioMatch) {
      current = { id: scenarioMatch[1], title: scenarioMatch[2], steps: [], line: block.line + offset + 1 };
      currentKeyword = 'Given';
      scenarios.push(current);
      continue;
    }

    if (!current) continue;
    const stepMatch = STEP_RE.exec(line);
    if (stepMatch) {
      const keyword = stepMatch[1];
      if (keyword === 'Given' || keyword === 'When' || keyword === 'Then') currentKeyword = keyword;
      current.steps.push({ keyword: currentKeyword, originalKeyword: keyword, text: stepMatch[2] });
    }
  }

  return {
    area,
    subarea,
    tags: [...new Set(tags)],
    name,
    scenarios,
    line: block.line,
  };
}

function canonicalizeKeywords(scenarios) {
  const keywordsByText = new Map();
  for (const scenario of scenarios) {
    for (const step of scenario.steps) {
      const set = keywordsByText.get(step.text) ?? new Set();
      set.add(step.keyword);
      keywordsByText.set(step.text, set);
    }
  }
  const canonical = new Map();
  for (const [text, keywords] of keywordsByText) {
    if (keywords.has('Then')) canonical.set(text, 'Then');
    else if (keywords.has('When')) canonical.set(text, 'When');
    else if (keywords.has('Given')) canonical.set(text, 'Given');
    else canonical.set(text, 'Given');
  }
  for (const scenario of scenarios) {
    for (const step of scenario.steps) {
      step.keyword = canonical.get(step.text) ?? step.keyword;
    }
  }
}

export function parseBdd(markdown, options = {}) {
  const expectedCount = options.expectedCount ?? EXPECTED_SCENARIO_COUNT;
  const lines = markdown.split(/\r?\n/);
  const features = [];
  let area = null;
  let subarea = null;
  let inGherkin = false;
  let block = null;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (!inGherkin) {
      const areaMatch = /^##\s+(\d+)\.\s+(.+?)\s*$/.exec(line);
      if (areaMatch) {
        area = { number: String(Number(areaMatch[1])).padStart(2, '0'), title: areaMatch[2] };
        subarea = null;
        continue;
      }
      const subareaMatch = /^###\s+(\d+\.\d+)\s+(.+?)\s*$/.exec(line);
      if (subareaMatch) {
        subarea = { number: subareaMatch[1], title: subareaMatch[2] };
        continue;
      }
      if (/^```gherkin\s*$/.test(line)) {
        inGherkin = true;
        block = { line: index + 1, lines: [] };
      }
      continue;
    }

    if (/^```\s*$/.test(line)) {
      inGherkin = false;
      if (block) {
        features.push(parseBlock(block, area, subarea));
        block = null;
      }
      continue;
    }
    block.lines.push(line);
  }

  const scenarios = features.flatMap((feature) => feature.scenarios);
  canonicalizeKeywords(scenarios);
  if (options.suiteByScenario instanceof Map) {
    for (const scenario of scenarios) {
      const suite = options.suiteByScenario.get(scenario.id);
      if (suite) scenario.suite = suite;
    }
  }
  const errors = [];
  const ids = scenarios.map((scenario) => scenario.id);
  const seen = new Map();
  for (const id of ids) {
    seen.set(id, (seen.get(id) ?? 0) + 1);
  }
  for (const [id, count] of seen) {
    if (count > 1) errors.push(`duplicate scenario id ${id} (${count} occurrences)`);
  }

  const expectedIds = Array.from({ length: expectedCount }, (_, i) => `E2E-${String(i + 1).padStart(3, '0')}`);
  const expectedSet = new Set(expectedIds);
  for (const id of ids) {
    if (!expectedSet.has(id)) errors.push(`unexpected scenario id ${id}`);
  }
  for (const id of expectedIds) {
    if (!seen.has(id)) errors.push(`missing scenario id ${id}`);
  }
  if (scenarios.length !== expectedCount) {
    errors.push(`expected ${expectedCount} scenarios but found ${scenarios.length}`);
  }

  for (const feature of features) {
    if (!feature.name) errors.push(`feature without a Feature line near BDD.md line ${feature.line}`);
    for (const scenario of feature.scenarios) {
      if (!scenario.steps.some((step) => step.keyword === 'Then')) {
        errors.push(`scenario ${scenario.id} has no Then step`);
      }
    }
  }

  return { features, scenarios, errors, expectedCount };
}

export function assignFileNames(features) {
  const used = new Set();
  const result = [];
  for (const feature of features) {
    const areaNumber = feature.area?.number ?? '00';
    const subNumber = feature.subarea ? `.${feature.subarea.number.split('.')[1]}` : '';
    const namePart = slugify(feature.name || feature.area?.title || 'feature');
    let base = `${areaNumber}${subNumber}-${namePart}`;
    if (!base.endsWith('.feature')) base += '.feature';
    let candidate = base;
    let n = 2;
    while (used.has(candidate)) {
      candidate = base.replace(/\.feature$/, `-${n}.feature`);
      n += 1;
    }
    used.add(candidate);
    result.push({ ...feature, fileName: candidate });
  }
  return result;
}

export function renderFeature(feature) {
  const lines = [];
  if (feature.tags.length > 0) lines.push(feature.tags.join(' '));
  lines.push(`Feature: ${feature.name}`);
  lines.push('');
  for (const scenario of feature.scenarios) {
    lines.push(`  @${scenario.id}${scenario.suite ? ` @suite-${scenario.suite}` : ''}`);
    lines.push(`  Scenario: ${scenario.id} ${scenario.title}`);
    for (const step of scenario.steps) {
      lines.push(`    ${step.keyword} ${step.text}`);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function buildFeatures(markdown, options = {}) {
  const { features, scenarios, errors, expectedCount } = parseBdd(markdown, options);
  const named = assignFileNames(features);
  const files = new Map();
  for (const feature of named) {
    files.set(feature.fileName, renderFeature(feature));
  }
  return { features: named, scenarios, errors, expectedCount, files };
}

export function hashContent(value) {
  return createHash('sha256').update(value).digest('hex');
}

export function summarize(files, scenarios) {
  return {
    features: files.size,
    scenarios: scenarios.length,
    hash: hashContent([...files.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, content]) => `${name}\n${content}`).join('\n')),
  };
}
