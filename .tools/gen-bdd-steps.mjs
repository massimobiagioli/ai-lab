#!/usr/bin/env node
// Generate exact-match step definitions for the narrative BDD scenarios that
// do not yet have a curated step definition.
//
// Usage:
//   node .tools/gen-bdd-steps.mjs --check [--root DIR] [--expected N]
//   node .tools/gen-bdd-steps.mjs --write [--root DIR] [--expected N]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildFeatures, EXPECTED_SCENARIO_COUNT } from './lib/bdd-parser.mjs';
import { computeCoverage, loadStepDefinitions, stepKey } from './lib/step-parser.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(HERE, '..');
const GENERATED_FILE = 'generated.steps.ts';

function usage() {
  process.stdout.write(`Usage: node .tools/gen-bdd-steps.mjs --check|--write [options]

Options:
  --check        Verify that generated.steps.ts matches the pending inventory.
  --write        Regenerate web/e2e-bdd/steps/generated.steps.ts.
  --root DIR     Repository root (default: ${DEFAULT_ROOT}).
  --expected N   Expected scenario count (default: ${EXPECTED_SCENARIO_COUNT}).
  --help         Show this help.

Exit codes:
  0  OK
  1  drift, invalid source or invalid arguments
`);
}

function parseArgs(argv) {
  const args = { root: DEFAULT_ROOT, expected: EXPECTED_SCENARIO_COUNT, mode: null };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') return { help: true, args };
    if (arg === '--check') args.mode = 'check';
    else if (arg === '--write') args.mode = 'write';
    else if (arg === '--root') args.root = resolve(argv[++i] ?? '');
    else if (arg === '--expected') args.expected = Number(argv[++i]);
    else return { error: `unknown argument: ${arg}`, args };
  }
  if (!args.mode) return { error: 'one of --check or --write is required', args };
  if (!Number.isInteger(args.expected) || args.expected < 1) return { error: '--expected must be a positive integer', args };
  return { args };
}

function fail(message) {
  process.stderr.write(`gen-bdd-steps: ${message}\n`);
  process.exit(1);
}

function regexLiteral(value) {
  return value.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

function render(pending) {
  const lines = [
    '// Generated by .tools/gen-bdd-steps.mjs from .docs/e2e/BDD.md.',
    '// Do not edit by hand. Regenerate with: node .tools/gen-bdd-steps.mjs --write',
    "import { createBdd } from 'playwright-bdd';",
    "import { test } from '../support/fixtures';",
    "import { handleGeneratedStep } from '../support/generated-step-handler';",
    '',
    'const { Given, When, Then } = createBdd(test);',
    '',
  ];
  const order = { Given: 0, When: 1, Then: 2 };
  pending
    .sort((a, b) => (order[a.keyword] ?? 9) - (order[b.keyword] ?? 9) || a.text.localeCompare(b.text))
    .forEach((step) => {
      lines.push(`${step.keyword}(/^${regexLiteral(step.text)}$/, async ({ api, page, world }) => {`);
      lines.push(`  await handleGeneratedStep(${JSON.stringify(step.keyword)}, ${JSON.stringify(step.text)}, { api, page, world });`);
      lines.push('});');
      lines.push('');
    });
  return `${lines.join('\n').trimEnd()}\n`;
}

function main() {
  const parsed = parseArgs(process.argv.slice(2));
  if (parsed.help) {
    usage();
    return;
  }
  if (parsed.error) fail(parsed.error);
  const { root, expected, mode } = parsed.args;
  const sourceFile = join(root, '.docs', 'e2e', 'BDD.md');
  const stepDir = join(root, 'web', 'e2e-bdd', 'steps');
  const target = join(stepDir, GENERATED_FILE);

  if (!existsSync(sourceFile)) fail(`missing source: ${sourceFile}`);
  const markdown = readFileSync(sourceFile, 'utf8');
  const { files, scenarios, errors } = buildFeatures(markdown, { expectedCount: expected });
  if (errors.length > 0) {
    process.stderr.write(`gen-bdd-steps: invalid BDD source:\n${errors.map((e) => `  - ${e}`).join('\n')}\n`);
    process.exit(1);
  }
  if (files.size === 0) fail('no generated features found');

  const curated = loadStepDefinitions(stepDir, { excludeFiles: [GENERATED_FILE] });
  const coverage = computeCoverage(scenarios, curated);
  const pendingMap = new Map();
  for (const step of coverage.unmatchedSteps) {
    pendingMap.set(stepKey(step.keyword, step.text), step);
  }
  const pending = [...pendingMap.values()];
  const content = render(pending);

  if (mode === 'write') {
    mkdirSync(stepDir, { recursive: true });
    writeFileSync(target, content, 'utf8');
    process.stdout.write(`gen-bdd-steps: wrote ${pending.length} generated step definitions to web/e2e-bdd/steps/${GENERATED_FILE}\n`);
    return;
  }

  if (!existsSync(target)) {
    process.stderr.write(`gen-bdd-steps: missing ${target}; run --write.\n`);
    process.exit(1);
  }
  if (readFileSync(target, 'utf8') !== content) {
    process.stderr.write('gen-bdd-steps: generated.steps.ts is out of date; run --write.\n');
    process.exit(1);
  }
  process.stdout.write(`gen-bdd-steps: OK (${pending.length} generated steps)\n`);
}

main();
